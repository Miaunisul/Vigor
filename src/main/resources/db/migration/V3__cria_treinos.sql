CREATE TABLE treinos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    membro_id BIGINT NOT NULL,
    tipo TEXT NOT NULL,
    descricao TEXT NOT NULL,
    duracao_minutos INTEGER NOT NULL,
    data_inicio DATE NOT NULL,

    CONSTRAINT ck_treinos_tipo_nao_vazio
        CHECK (btrim(tipo) <> ''),
    CONSTRAINT ck_treinos_descricao_nao_vazia
        CHECK (btrim(descricao) <> ''),
    CONSTRAINT ck_treinos_duracao_positiva
        CHECK (duracao_minutos > 0),
    CONSTRAINT fk_treinos_membros
        FOREIGN KEY (membro_id)
        REFERENCES membros (id)
        ON DELETE RESTRICT
);

CREATE INDEX idx_treinos_membro_id
    ON treinos (membro_id);
