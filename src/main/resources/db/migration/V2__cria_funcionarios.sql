CREATE TABLE funcionarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    cargo TEXT NOT NULL,
    login TEXT NOT NULL,
    senha_hash TEXT NOT NULL,

    CONSTRAINT ck_funcionarios_nome_nao_vazio
        CHECK (btrim(nome) <> ''),
    CONSTRAINT ck_funcionarios_cargo_nao_vazio
        CHECK (btrim(cargo) <> ''),
    CONSTRAINT ck_funcionarios_login_nao_vazio
        CHECK (btrim(login) <> ''),
    CONSTRAINT ck_funcionarios_senha_hash_nao_vazio
        CHECK (btrim(senha_hash) <> '')
);

CREATE UNIQUE INDEX ux_funcionarios_login_normalizado
    ON funcionarios (lower(btrim(login)));
