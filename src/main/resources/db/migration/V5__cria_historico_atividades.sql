CREATE TABLE historico_atividades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    membro_id BIGINT NOT NULL,
    funcionario_responsavel_id BIGINT NOT NULL,
    atividade TEXT NOT NULL,
    data_atividade DATE NOT NULL,
    tempo_execucao_minutos INTEGER NOT NULL,

    CONSTRAINT ck_historico_atividades_atividade_nao_vazia
        CHECK (btrim(atividade) <> ''),
    CONSTRAINT ck_historico_atividades_tempo_positivo
        CHECK (tempo_execucao_minutos > 0),
    CONSTRAINT fk_historico_atividades_membros
        FOREIGN KEY (membro_id)
        REFERENCES membros (id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_historico_atividades_funcionarios
        FOREIGN KEY (funcionario_responsavel_id)
        REFERENCES funcionarios (id)
        ON DELETE RESTRICT
);

CREATE INDEX idx_historico_atividades_membro_id
    ON historico_atividades (membro_id);
