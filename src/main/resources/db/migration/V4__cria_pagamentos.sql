CREATE TABLE pagamentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    membro_id BIGINT NOT NULL,
    valor NUMERIC(12, 2) NOT NULL,
    data_pagamento DATE NOT NULL,
    status VARCHAR(4) NOT NULL,

    CONSTRAINT ck_pagamentos_valor_positivo
        CHECK (valor > 0),
    CONSTRAINT ck_pagamentos_status_pago
        CHECK (status = 'PAGO'),
    CONSTRAINT fk_pagamentos_membros
        FOREIGN KEY (membro_id)
        REFERENCES membros (id)
        ON DELETE RESTRICT
);

CREATE INDEX idx_pagamentos_membro_id
    ON pagamentos (membro_id);
